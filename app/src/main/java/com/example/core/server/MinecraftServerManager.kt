package com.example.core.server

import android.content.Context
import android.os.Environment
import android.util.Log
import com.example.core.runtime.JdkManager
import kotlinx.coroutines.CoroutineScope
import kotlinx.coroutines.Dispatchers
import kotlinx.coroutines.Job
import kotlinx.coroutines.delay
import kotlinx.coroutines.flow.MutableSharedFlow
import kotlinx.coroutines.flow.MutableStateFlow
import kotlinx.coroutines.flow.SharedFlow
import kotlinx.coroutines.flow.StateFlow
import kotlinx.coroutines.flow.asSharedFlow
import kotlinx.coroutines.flow.asStateFlow
import kotlinx.coroutines.launch
import kotlinx.coroutines.withContext
import okhttp3.OkHttpClient
import okhttp3.Request
import org.json.JSONObject
import java.io.BufferedReader
import java.io.BufferedWriter
import java.io.File
import java.io.FileOutputStream
import java.io.InputStreamReader
import java.io.OutputStreamWriter
import java.util.concurrent.ConcurrentLinkedQueue

enum class ServerStatus {
    STOPPED,
    DOWNLOADING_ENGINE,
    STARTING,
    RUNNING,
    STOPPING,
    CRASHED
}

data class ServerState(
    val status: ServerStatus = ServerStatus.STOPPED,
    val selectedVersion: String = "1.20.4",
    val availableVersions: List<String> = listOf("1.20.4", "1.20.6", "1.21", "1.21.1", "1.19.4"),
    val allocatedRamGb: Int = 4,
    val onlinePlayers: Set<String> = emptySet(),
    val maxPlayers: Int = 20,
    val port: Int = 25565,
    val engineDownloadProgress: Float = 0f,
    val statusMessage: String = "Server stopped",
    val recentLogs: List<String> = emptyList(),
    val crashCount: Int = 0
)

class MinecraftServerManager(
    private val context: Context,
    private val jdkManager: JdkManager,
    private val scope: CoroutineScope,
    private val onPlayerLeft: (String) -> Unit
) {
    companion object {
        private const val TAG = "MinecraftServerManager"
        private const val PAPER_API_BASE = "https://api.papermc.io/v2/projects/paper"
    }

    private val _state = MutableStateFlow(ServerState())
    val state: StateFlow<ServerState> = _state.asStateFlow()

    private val _logBroadcast = MutableSharedFlow<String>(replay = 50, extraBufferCapacity = 500)
    val logBroadcast: SharedFlow<String> = _logBroadcast.asSharedFlow()

    private val logBuffer = ConcurrentLinkedQueue<String>()
    private val httpClient = OkHttpClient.Builder().build()

    private var process: Process? = null
    private var processWriter: BufferedWriter? = null
    private var processJob: Job? = null

    val serverDirectory: File
        get() {
            val extDir = File(Environment.getExternalStorageDirectory(), "MinecraftServer")
            return if (Environment.isExternalStorageManager() || extDir.canWrite()) {
                extDir.mkdirs()
                extDir
            } else {
                val appSpecific = context.getExternalFilesDir("MinecraftServer") ?: File(context.filesDir, "MinecraftServer")
                appSpecific.mkdirs()
                appSpecific
            }
        }

    val serverJarFile: File
        get() = File(serverDirectory, "paper.jar")

    fun initServerFiles() {
        val dir = serverDirectory
        dir.mkdirs()
        File(dir, "plugins").mkdirs()
        File(dir, "backups").mkdirs()
        File(dir, "logs").mkdirs()

        // Write EULA
        val eulaFile = File(dir, "eula.txt")
        eulaFile.writeText("# By changing the setting below to TRUE you are indicating your agreement to the Mojang EULA.\neula=true\n")

        // Default server.properties if not exists
        val propsFile = File(dir, "server.properties")
        if (!propsFile.exists()) {
            propsFile.writeText(
                """
                # Minecraft server properties generated by MC-Droid Host
                server-port=25565
                gamemode=survival
                difficulty=easy
                motd=MC-Droid Host Dedicated Server
                max-players=20
                online-mode=true
                enable-command-block=true
                spawn-protection=0
                view-distance=8
                simulation-distance=6
                sync-chunk-writes=false
                """.trimIndent()
            )
        }
    }

    suspend fun fetchPaperVersions(): List<String> = withContext(Dispatchers.IO) {
        try {
            val request = Request.Builder().url(PAPER_API_BASE).build()
            httpClient.newCall(request).execute().use { resp ->
                if (!resp.isSuccessful) return@withContext _state.value.availableVersions
                val json = JSONObject(resp.body?.string() ?: "")
                val versionsArray = json.getJSONArray("versions")
                val list = mutableListOf<String>()
                for (i in 0 until versionsArray.length()) {
                    list.add(versionsArray.getString(i))
                }
                val reversed = list.reversed()
                _state.value = _state.value.copy(availableVersions = reversed)
                reversed
            }
        } catch (e: Exception) {
            Log.w(TAG, "Failed fetching Paper versions", e)
            _state.value.availableVersions
        }
    }

    suspend fun downloadPaperJar(version: String): Boolean = withContext(Dispatchers.IO) {
        _state.value = _state.value.copy(
            status = ServerStatus.DOWNLOADING_ENGINE,
            statusMessage = "Resolving latest Paper $version build...",
            engineDownloadProgress = 0f
        )
        try {
            // 1. Get latest build for version
            val versionUrl = "$PAPER_API_BASE/versions/$version"
            val buildReq = Request.Builder().url(versionUrl).build()
            val latestBuild: Int = httpClient.newCall(buildReq).execute().use { resp ->
                val json = JSONObject(resp.body?.string() ?: "")
                val builds = json.getJSONArray("builds")
                builds.getInt(builds.length() - 1)
            }

            // 2. Get download name
            val buildUrl = "$PAPER_API_BASE/versions/$version/builds/$latestBuild"
            val fileReq = Request.Builder().url(buildUrl).build()
            val jarName: String = httpClient.newCall(fileReq).execute().use { resp ->
                val json = JSONObject(resp.body?.string() ?: "")
                val downloads = json.getJSONObject("downloads")
                val app = downloads.getJSONObject("application")
                app.getString("name")
            }

            // 3. Download the jar
            val downloadUrl = "$PAPER_API_BASE/versions/$version/builds/$latestBuild/downloads/$jarName"
            _state.value = _state.value.copy(statusMessage = "Downloading Paper $version (Build $latestBuild)...")

            initServerFiles()
            val request = Request.Builder().url(downloadUrl).build()
            httpClient.newCall(request).execute().use { resp ->
                if (!resp.isSuccessful) throw IllegalStateException("Download failed HTTP ${resp.code}")
                val body = resp.body ?: throw IllegalStateException("Empty body")
                val totalLength = body.contentLength()

                val tempJar = File(serverDirectory, "paper.jar.tmp")
                FileOutputStream(tempJar).use { fos ->
                    val buffer = ByteArray(32 * 1024)
                    var read: Int
                    var current = 0L
                    val inStream = body.byteStream()
                    while (inStream.read(buffer).also { read = it } != -1) {
                        fos.write(buffer, 0, read)
                        current += read
                        val progress = if (totalLength > 0) current.toFloat() / totalLength else 0f
                        _state.value = _state.value.copy(
                            engineDownloadProgress = progress,
                            statusMessage = "Downloading Paper engine: ${(progress * 100).toInt()}%"
                        )
                    }
                }
                tempJar.renameTo(serverJarFile)
            }

            _state.value = _state.value.copy(
                status = ServerStatus.STOPPED,
                statusMessage = "Paper $version ready",
                selectedVersion = version,
                engineDownloadProgress = 1f
            )
            true
        } catch (e: Exception) {
            Log.e(TAG, "Paper jar download error", e)
            _state.value = _state.value.copy(
                status = ServerStatus.STOPPED,
                statusMessage = "Download error: ${e.message}"
            )
            false
        }
    }

    fun startServer(ramGb: Int = _state.value.allocatedRamGb) {
        if (_state.value.status == ServerStatus.RUNNING || _state.value.status == ServerStatus.STARTING) return

        initServerFiles()
        if (!serverJarFile.exists()) {
            scope.launch {
                val ok = downloadPaperJar(_state.value.selectedVersion)
                if (ok) startServerProcess(ramGb)
            }
            return
        }

        startServerProcess(ramGb)
    }

    private fun startServerProcess(ramGb: Int) {
        processJob = scope.launch(Dispatchers.IO) {
            try {
                _state.value = _state.value.copy(
                    status = ServerStatus.STARTING,
                    allocatedRamGb = ramGb,
                    statusMessage = "Starting Minecraft Server (${ramGb}G RAM)...",
                    onlinePlayers = emptySet()
                )

                val javaBin = jdkManager.javaExecutable
                if (!javaBin.exists()) {
                    appendLog("[ERROR] Java binary not found! Please install OpenJDK 21 first.")
                    _state.value = _state.value.copy(
                        status = ServerStatus.STOPPED,
                        statusMessage = "JDK 21 missing"
                    )
                    return@launch
                }

                // Aikar ARM-optimized JVM Flags
                val cmd = mutableListOf(
                    javaBin.absolutePath,
                    "-Xms2G",
                    "-Xmx${ramGb}G",
                    "-XX:+UseG1GC",
                    "-XX:+ParallelRefProcEnabled",
                    "-XX:MaxGCPauseMillis=200",
                    "-XX:+UnlockExperimentalVMOptions",
                    "-XX:+DisableExplicitGC",
                    "-jar",
                    serverJarFile.absolutePath,
                    "--nogui"
                )

                val pb = ProcessBuilder(cmd)
                pb.directory(serverDirectory)
                val env = pb.environment()
                val libDir = File(jdkManager.runtimeDir, "lib")
                val jvmDir = File(libDir, "server")
                env["LD_LIBRARY_PATH"] = "${libDir.absolutePath}:${jvmDir.absolutePath}"
                env["HOME"] = context.filesDir.absolutePath
                pb.redirectErrorStream(true)

                appendLog("[MC-DROID] Spawning Java Process: ${cmd.joinToString(" ")}")
                val p = pb.start()
                process = p
                processWriter = BufferedWriter(OutputStreamWriter(p.outputStream))

                val reader = BufferedReader(InputStreamReader(p.inputStream))
                var line: String?
                while (reader.readLine().also { line = it } != null) {
                    line?.let { handleServerOutput(it) }
                }

                val exitCode = p.waitFor()
                appendLog("[MC-DROID] Server process terminated with exit code $exitCode")

                if (exitCode != 0 && _state.value.status != ServerStatus.STOPPING) {
                    _state.value = _state.value.copy(
                        status = ServerStatus.CRASHED,
                        statusMessage = "Server crashed (exit code $exitCode)",
                        crashCount = _state.value.crashCount + 1
                    )
                } else {
                    _state.value = _state.value.copy(
                        status = ServerStatus.STOPPED,
                        statusMessage = "Server stopped cleanly",
                        onlinePlayers = emptySet()
                    )
                }
            } catch (e: Exception) {
                Log.e(TAG, "Server execution failed", e)
                appendLog("[EXCEPTION] ${e.message}")
                _state.value = _state.value.copy(
                    status = ServerStatus.CRASHED,
                    statusMessage = "Execution failure: ${e.message}"
                )
            } finally {
                process = null
                processWriter = null
            }
        }
    }

    private fun handleServerOutput(line: String) {
        appendLog(line)

        // Startup complete pattern
        if (line.contains("Done (") || line.contains("For help, type \"help\"")) {
            _state.value = _state.value.copy(
                status = ServerStatus.RUNNING,
                statusMessage = "Server Online (Port ${_state.value.port})"
            )
        }

        // Player joined
        if (line.contains("joined the game")) {
            val name = extractPlayerName(line, "joined the game")
            if (name != null) {
                _state.value = _state.value.copy(
                    onlinePlayers = _state.value.onlinePlayers + name
                )
            }
        }

        // Player left
        if (line.contains("left the game")) {
            val name = extractPlayerName(line, "left the game")
            if (name != null) {
                _state.value = _state.value.copy(
                    onlinePlayers = _state.value.onlinePlayers - name
                )
                onPlayerLeft(name)
            }
        }
    }

    private fun extractPlayerName(line: String, token: String): String? {
        val idx = line.indexOf(token)
        if (idx == -1) return null
        val before = line.substring(0, idx).trim()
        val parts = before.split(" ", ":")
        return parts.lastOrNull()?.trim()?.replace("[", "")?.replace("]", "")
    }

    fun sendCommand(cmd: String) {
        val trimmed = cmd.trim()
        if (trimmed.isEmpty()) return
        appendLog("> $trimmed")
        scope.launch(Dispatchers.IO) {
            try {
                processWriter?.let { writer ->
                    writer.write(trimmed)
                    writer.newLine()
                    writer.flush()
                }
            } catch (e: Exception) {
                Log.e(TAG, "Error writing command to stdin", e)
            }
        }
    }

    fun stopServer() {
        if (_state.value.status != ServerStatus.RUNNING && _state.value.status != ServerStatus.STARTING) return
        _state.value = _state.value.copy(
            status = ServerStatus.STOPPING,
            statusMessage = "Stopping server cleanly..."
        )
        sendCommand("stop")

        scope.launch(Dispatchers.IO) {
            delay(10000)
            if (process != null && process?.isAlive == true) {
                appendLog("[MC-DROID] Process did not exit in 10s, forcing destroy...")
                process?.destroy()
            }
        }
    }

    fun restartServer(ramGb: Int = _state.value.allocatedRamGb) {
        scope.launch {
            stopServer()
            while (process != null && process?.isAlive == true) {
                delay(500)
            }
            delay(1000)
            startServer(ramGb)
        }
    }

    fun appendLog(line: String) {
        logBuffer.add(line)
        while (logBuffer.size > 1000) {
            logBuffer.poll()
        }
        _state.value = _state.value.copy(recentLogs = logBuffer.toList().takeLast(100))
        scope.launch {
            _logBroadcast.emit(line)
        }
    }

    fun clearLogs() {
        logBuffer.clear()
        _state.value = _state.value.copy(recentLogs = emptyList())
    }
}
