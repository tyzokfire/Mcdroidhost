    /**
     * Starts the Minecraft server. Auto-generates server files and downloads Paper jar
     * if it's the first launch or after a reset.
     */
    fun startServer(ramGb: Int = _state.value.allocatedRamGb) {
        if (_state.value.status == ServerStatus.RUNNING || _state.value.status == ServerStatus.STARTING || _state.value.status == ServerStatus.DOWNLOADING_ENGINE) {
            appendLog("[INFO] Une opération est déjà en cours (statut: ${_state.value.status}).")
            return
        }

        _state.value = _state.value.copy(
            status = ServerStatus.STARTING,
            allocatedRamGb = ramGb,
            statusMessage = "Démarrage du serveur en cours..."
        )

        scope.launch {
            runSystemDiagnostics()

            // 1. Auto-install OpenJDK 21 if missing
            if (!jdkManager.checkInstallation()) {
                appendLog("[DIAGNOSTIC] OpenJDK 21 manquant. Démarrage du téléchargement automatique...")
                _state.value = _state.value.copy(
                    status = ServerStatus.DOWNLOADING_ENGINE,
                    statusMessage = "Téléchargement d'OpenJDK 21...",
                    engineDownloadProgress = 0f
                )
                val jdkOk = jdkManager.downloadAndInstall()
                if (!jdkOk) {
                    appendLog("[ERREUR CRITIQUE] Échec de l'installation d'OpenJDK 21.")
                    _state.value = _state.value.copy(
                        status = ServerStatus.STOPPED,
                        statusMessage = "Échec installation OpenJDK 21",
                        engineDownloadProgress = 0f
                    )
                    return@launch
                }
                appendLog("[SUCCÈS] OpenJDK 21 installé avec succès.")
            }

            // 2. Ensure server directories and configs exist
            initServerFiles()

            // 3. Auto-download Paper engine if missing
            if (!serverJarFile.exists() || serverJarFile.length() < 5 * 1024 * 1024) {
                appendLog("[DIAGNOSTIC] Aucun fichier paper.jar valide détecté. Téléchargement de Paper ${_state.value.selectedVersion}...")
                val paperOk = downloadPaperJar(_state.value.selectedVersion)
                if (!paperOk) {
                    appendLog("[ERREUR CRITIQUE] Échec du téléchargement du moteur Paper.")
                    _state.value = _state.value.copy(
                        status = ServerStatus.STOPPED,
                        statusMessage = "Échec téléchargement Paper",
                        engineDownloadProgress = 0f
                    )
                    return@launch
                }
                appendLog("[SUCCÈS] Moteur Paper installé avec succès.")
            }

            // 4. Launch Java process
            startServerProcess(ramGb)
        }
    }

    private fun startServerProcess(ramGb: Int) {
        processJob = scope.launch(Dispatchers.IO) {
            try {
                _state.value = _state.value.copy(
                    status = ServerStatus.STARTING,
                    allocatedRamGb = ramGb,
                    statusMessage = "Démarrage du serveur Java (${ramGb}G RAM)...",
                    onlinePlayers = emptySet()
                )

                val javaBin = jdkManager.javaExecutable
                if (!javaBin.exists()) {
                    appendLog("[ERREUR] Binaire Java introuvable dans: ${javaBin.absolutePath}")
                    _state.value = _state.value.copy(
                        status = ServerStatus.STOPPED,
                        statusMessage = "OpenJDK 21 manquant"
                    )
                    return@launch
                }

                // Make sure execution permissions are granted
                jdkManager.applyExecPermissions(jdkManager.runtimeDir)
                if (!javaBin.canExecute()) {
                    javaBin.setExecutable(true, false)
                }

                // Temp directory inside app internal cache (mandatory for Android JVM & Netty native extraction)
                val tmpDir = File(context.cacheDir, "mc_tmp").apply { mkdirs() }

                // Safe initial heap (512M) + max heap (ramGb) to avoid immediate virtual memory abort on mobile Linux
                val cmd = mutableListOf(
                    javaBin.absolutePath,
                    "-Xms512M",
                    "-Xmx${ramGb}G",
                    "-Djava.io.tmpdir=${tmpDir.absolutePath}",
                    "-Duser.home=${context.filesDir.absolutePath}",
                    "-XX:+UseG1GC",
                    "-XX:+ParallelRefProcEnabled",
                    "-XX:MaxGCPauseMillis=200",
                    "-XX:+UnlockExperimentalVMOptions",
                    "-XX:+DisableExplicitGC",
                    "-jar",
                    serverJarFile.absolutePath,
                    "--nogui"
                )

                val pb = ProcessBuilder(cmd)
                pb.directory(serverDirectory)
                val env = pb.environment()

                // Inject dynamic libraries so libjvm.so, libjli.so, and Android Bionic libc are found
                val libDir = File(jdkManager.runtimeDir, "lib")
                val jvmDir = File(libDir, "server")
                val jliDir = File(libDir, "jli")
                val ldDirs = mutableListOf<String>()
                if (jvmDir.exists()) ldDirs.add(jvmDir.absolutePath)
                if (libDir.exists()) ldDirs.add(libDir.absolutePath)
                if (jliDir.exists()) ldDirs.add(jliDir.absolutePath)
                ldDirs.add(context.applicationInfo.nativeLibraryDir)
                ldDirs.add("/system/lib64")
                ldDirs.add("/apex/com.android.runtime/lib64")

                env["LD_LIBRARY_PATH"] = ldDirs.joinToString(":")
                env["JAVA_HOME"] = jdkManager.runtimeDir.absolutePath
                env["PATH"] = "${context.applicationInfo.nativeLibraryDir}:${jdkManager.binDir.absolutePath}:${System.getenv("PATH") ?: "/system/bin"}"
                env["HOME"] = context.filesDir.absolutePath
                env["TMPDIR"] = tmpDir.absolutePath
                pb.redirectErrorStream(true)

                appendLog("[DIAGNOSTIC] Répertoire de travail: ${serverDirectory.absolutePath}")
                appendLog("[DIAGNOSTIC] Commande JVM: ${cmd.joinToString(" ")}")
                appendLog("[DIAGNOSTIC] LD_LIBRARY_PATH: ${env["LD_LIBRARY_PATH"]}")
                appendLog("[MC-DROID] Lancement du processus Java...")

                val p = pb.start()
                process = p
                processWriter = BufferedWriter(OutputStreamWriter(p.outputStream))

                val reader = BufferedReader(InputStreamReader(p.inputStream))
                var line: String?
                while (reader.readLine().also { line = it } != null) {
                    line?.let { handleServerOutput(it) }
                }

                val exitCode = p.waitFor()
                val exitExplanation = when (exitCode) {
                    0 -> "Arrêt propre (code 0)"
                    1 -> "Erreur de configuration ou crash Java non géré"
                    126 -> "Permission d'exécution refusée (chmod manquant sur le binaire java)"
                    127 -> "Binaire introuvable ou bibliothèque dynamique manquante"
                    137 -> "Arrêté par Android OOM Killer (Manque de RAM). Réduisez la mémoire allouée (ex: 3-4 GB)."
                    143 -> "Arrêté via SIGTERM (Signal d'interruption)"
                    else -> "Code de sortie $exitCode"
                }

                appendLog("[MC-DROID] Le processus serveur s'est terminé: $exitExplanation")

                if (exitCode != 0 && _state.value.status != ServerStatus.STOPPING) {
                    _state.value = _state.value.copy(
                        status = ServerStatus.CRASHED,
                        statusMessage = "Crash serveur: $exitExplanation",
                        crashCount = _state.value.crashCount + 1
                    )
                } else {
                    _state.value = _state.value.copy(
                        status = ServerStatus.STOPPED,
                        statusMessage = "Serveur arrêté",
                        onlinePlayers = emptySet()
                    )
                }
            } catch (e: Exception) {
                Log.e(TAG, "Server execution failed", e)
                appendLog("[EXCEPTION DÉMARRAGE] ${e.javaClass.simpleName}: ${e.message}")
                _state.value = _state.value.copy(
                    status = ServerStatus.CRASHED,
                    statusMessage = "Erreur d'exécution: ${e.message}"
                )
            } finally {
                process = null
                processWriter = null
            }
        }
    }

    private fun handleServerOutput(line: String) {
        appendLog(line)

        // Server ready detection
        if (line.contains("Done (") || line.contains("For help, type \"help\"")) {
            _state.value = _state.value.copy(
                status = ServerStatus.RUNNING,
                statusMessage = "Serveur en ligne (Port ${_state.value.port})"
            )
            appendLog("[SUCCÈS] Le serveur Minecraft est PRÊT et écoute sur le port ${_state.value.port}!")
        }

        // Player joined
        if (line.contains("joined the game")) {
            val name = extractPlayerName(line, "joined the game")
            if (name != null) {
                _state.value = _state.value.copy(
                    onlinePlayers = _state.value.onlinePlayers + name
                )
            }
        }

        // Player left
        if (line.contains("left the game")) {
            val name = extractPlayerName(line, "left the game")
            if (name != null) {
                _state.value = _state.value.copy(
                    onlinePlayers = _state.value.onlinePlayers - name
                )
                onPlayerLeft(name)
            }
        }
    }

    private fun extractPlayerName(line: String, token: String): String? {
        val idx = line.indexOf(token)
        if (idx == -1) return null
        val before = line.substring(0, idx).trim()
        val parts = before.split(" ", ":")
        return parts.lastOrNull()?.trim()?.replace("[", "")?.replace("]", "")
    }

    fun sendCommand(cmd: String) {
        val trimmed = cmd.trim()
        if (trimmed.isEmpty()) return
        appendLog("> $trimmed")
        scope.launch(Dispatchers.IO) {
            try {
                processWriter?.let { writer ->
                    writer.write(trimmed)
                    writer.newLine()
                    writer.flush()
                }
            } catch (e: Exception) {
                Log.e(TAG, "Error writing command to stdin", e)
                appendLog("[ERREUR COMMANDE] ${e.message}")
            }
        }
    }

    fun stopServer() {
        if (_state.value.status != ServerStatus.RUNNING && _state.value.status != ServerStatus.STARTING) return
        _state.value = _state.value.copy(
            status = ServerStatus.STOPPING,
            statusMessage = "Arrêt propre du serveur en cours..."
        )
        appendLog("[MC-DROID] Envoi de la commande 'stop' au serveur...")
        sendCommand("stop")

        scope.launch(Dispatchers.IO) {
            delay(10000)
            if (process != null && process?.isAlive == true) {
                appendLog("[MC-DROID] Le processus n'a pas répondu sous 10s. Arrêt forcé...")
                process?.destroy()
            }
        }
    }

    fun restartServer(ramGb: Int = _state.value.allocatedRamGb) {
        scope.launch {
            appendLog("[MC-DROID] Redémarrage du serveur demandé...")
            stopServer()
            while (process != null && process?.isAlive == true) {
                delay(500)
            }
            delay(1000)
            startServer(ramGb)
        }
    }

    /**
     * Completely deletes all server files (world, configs, plugins, logs, paper.jar).
     * Allows the user to reset and generate a fresh server from scratch.
     */
    fun deleteServerFiles(): Boolean {
        return try {
            appendLog("[DIAGNOSTIC] === SUPPRESSION COMPLÈTE DU SERVEUR DEMANDÉE ===")
            if (process != null && process?.isAlive == true) {
                appendLog("[DIAGNOSTIC] Arrêt immédiat du processus en cours...")
                process?.destroyForcibly()
                process = null
                processWriter = null
            }
            processJob?.cancel()

            val dir = serverDirectory
            appendLog("[DIAGNOSTIC] Suppression du contenu de: ${dir.absolutePath}...")

            val files = dir.listFiles()
            files?.forEach { file ->
                val ok = file.deleteRecursively()
                appendLog("[DIAGNOSTIC] Suppression de ${file.name}: ${if (ok) "OK" else "Échec"}")
            }

            _state.value = _state.value.copy(
                status = ServerStatus.STOPPED,
                statusMessage = "Serveur supprimé. Prêt pour une nouvelle installation.",
                onlinePlayers = emptySet(),
                engineDownloadProgress = 0f
            )

            appendLog("[SUCCÈS] Le serveur a été TOTALEMENT supprimé.")
            appendLog("[INFO] Appuyez sur 'Start' pour générer un nouveau serveur fonctionnel tout neuf.")
            true
        } catch (e: Exception) {
            Log.e(TAG, "Failed to delete server files", e)
            appendLog("[ERREUR CRITIQUE] Échec de la suppression: ${e.message}")
            false
        }
    }

    val pluginsDirectory: File
        get() {
            val dir = File(serverDirectory, "plugins")
            dir.mkdirs()
            return dir
        }

    fun listPlugins(): List<File> {
        return pluginsDirectory.listFiles { f -> f.extension.equals("jar", ignoreCase = true) }
            ?.sortedBy { it.name.lowercase() } ?: emptyList()
    }

    fun deletePlugin(name: String): Boolean {
        val file = File(pluginsDirectory, name)
        if (!file.canonicalPath.startsWith(pluginsDirectory.canonicalPath)) {
            return false
        }
        return if (file.exists() && file.delete()) {
            appendLog("[PLUGIN] Plugin supprimé : $name")
            true
        } else {
            false
        }
    }

    fun installPlugin(inputStream: java.io.InputStream, fileName: String): Boolean {
        val safeName = fileName.replace("/", "").replace("\\", "").replace("..", "")
        if (!safeName.endsWith(".jar", ignoreCase = true)) return false

        val dest = File(pluginsDirectory, safeName)
        if (!dest.canonicalPath.startsWith(pluginsDirectory.canonicalPath)) return false

        return try {
            FileOutputStream(dest).use { fos ->
                inputStream.copyTo(fos)
            }
            appendLog("[PLUGIN] Plugin installé : $safeName (${dest.length() / 1024} Ko)")
            true
        } catch (e: Exception) {
            Log.e(TAG, "Failed installing plugin $safeName", e)
            appendLog("[PLUGIN-ERREUR] Échec de l'installation : ${e.message}")
            false
        }
    }

    fun appendLog(line: String) {
        logBuffer.add(line)
        while (logBuffer.size > 1000) {
            logBuffer.poll()
        }
        _state.value = _state.value.copy(recentLogs = logBuffer.toList().takeLast(100))
        scope.launch {
            _logBroadcast.emit(line)
        }
    }

    fun clearLogs() {
        logBuffer.clear()
        _state.value = _state.value.copy(recentLogs = emptyList())
        appendLog("[MC-DROID HOST] Console effacée.")
    }
