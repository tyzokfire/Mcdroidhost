    suspend fun fetchPaperVersions(): List<String> = withContext(Dispatchers.IO) {
        try {
            val request = Request.Builder().url(PAPER_API_BASE).build()
            httpClient.newCall(request).execute().use { resp ->
                if (!resp.isSuccessful) return@withContext _state.value.availableVersions
                val json = JSONObject(resp.body?.string() ?: "")
                val versionsArray = json.getJSONArray("versions")
                val list = mutableListOf<String>()
                for (i in 0 until versionsArray.length()) {
                    list.add(versionsArray.getString(i))
                }
                val reversed = list.reversed()
                _state.value = _state.value.copy(availableVersions = reversed)
                reversed
            }
        } catch (e: Exception) {
            Log.w(TAG, "Failed fetching Paper versions", e)
            _state.value.availableVersions
        }
    }

    /**
     * Downloads Paper engine with fallback mirror support and detailed diagnostic logging.
     */
    suspend fun downloadPaperJar(version: String): Boolean = withContext(Dispatchers.IO) {
        _state.value = _state.value.copy(
            status = ServerStatus.DOWNLOADING_ENGINE,
            statusMessage = "Téléchargement du moteur Paper $version...",
            engineDownloadProgress = 0f
        )
        appendLog("[DIAGNOSTIC] Début du téléchargement du moteur Minecraft Paper $version...")

        initServerFiles()
        val tempJar = File(serverDirectory, "paper.jar.tmp")
        if (tempJar.exists()) tempJar.delete()

        // 1. Try PaperMC official API
        var downloadSuccess = false
        try {
            appendLog("[DIAGNOSTIC] Connexion à l'API officielle PaperMC ($PAPER_API_BASE)...")
            val versionUrl = "$PAPER_API_BASE/versions/$version"
            val buildReq = Request.Builder().url(versionUrl).build()
            val latestBuild: Int = httpClient.newCall(buildReq).execute().use { resp ->
                if (!resp.isSuccessful) throw IllegalStateException("API Paper HTTP ${resp.code}")
                val json = JSONObject(resp.body?.string() ?: "")
                val builds = json.getJSONArray("builds")
                builds.getInt(builds.length() - 1)
            }

            val buildUrl = "$PAPER_API_BASE/versions/$version/builds/$latestBuild"
            val fileReq = Request.Builder().url(buildUrl).build()
            val jarName: String = httpClient.newCall(fileReq).execute().use { resp ->
                if (!resp.isSuccessful) throw IllegalStateException("Build info HTTP ${resp.code}")
                val json = JSONObject(resp.body?.string() ?: "")
                val downloads = json.getJSONObject("downloads")
                val app = downloads.getJSONObject("application")
                app.getString("name")
            }

            val downloadUrl = "$PAPER_API_BASE/versions/$version/builds/$latestBuild/downloads/$jarName"
            appendLog("[DIAGNOSTIC] Téléchargement depuis: $downloadUrl")
            downloadSuccess = executeFileDownload(downloadUrl, tempJar, "Paper $version (Build $latestBuild)")
        } catch (e: Exception) {
            appendLog("[ATTENTION] Échec PaperMC officiel: ${e.message}. Tentative avec le miroir alternatif PurpurMC...")
            Log.w(TAG, "Paper API download failed, trying Purpur fallback", e)
        }

        // 2. Fallback to Purpur (Drop-in Paper compatible fork) if primary failed
        if (!downloadSuccess) {
            try {
                val purpurUrl = "https://api.purpurmc.org/v2/purpur/$version/latest/download"
                appendLog("[DIAGNOSTIC] Connexion au miroir Purpur ($purpurUrl)...")
                downloadSuccess = executeFileDownload(purpurUrl, tempJar, "Purpur $version (Compatible Paper)")
            } catch (e2: Exception) {
                appendLog("[ERREUR] Échec du miroir de secours: ${e2.message}")
                Log.e(TAG, "Purpur fallback download failed", e2)
            }
        }

        if (downloadSuccess && tempJar.exists() && tempJar.length() > 5 * 1024 * 1024) {
            if (serverJarFile.exists()) serverJarFile.delete()
            tempJar.renameTo(serverJarFile)
            val sizeMb = serverJarFile.length() / (1024 * 1024)
            appendLog("[SUCCÈS] Moteur Paper installé avec succès (${sizeMb} Mo).")

            _state.value = _state.value.copy(
                status = ServerStatus.STOPPED,
                statusMessage = "Paper $version prêt (${sizeMb} Mo)",
                selectedVersion = version,
                engineDownloadProgress = 1f,
                serverPath = serverDirectory.absolutePath
            )
            true
        } else {
            tempJar.delete()
            appendLog("[ERREUR] Impossible de télécharger le moteur du serveur. Vérifiez la connexion Internet.")
            _state.value = _state.value.copy(
                status = ServerStatus.STOPPED,
                statusMessage = "Erreur téléchargement moteur",
                engineDownloadProgress = 0f
            )
            false
        }
    }

    private fun executeFileDownload(downloadUrl: String, destFile: File, label: String): Boolean {
        val request = Request.Builder().url(downloadUrl).build()
        httpClient.newCall(request).execute().use { resp ->
            if (!resp.isSuccessful) throw IllegalStateException("HTTP ${resp.code}")
            val body = resp.body ?: throw IllegalStateException("Réponse vide")
            val totalLength = body.contentLength()

            FileOutputStream(destFile).use { fos ->
                val buffer = ByteArray(64 * 1024)
                var read: Int
                var current = 0L
                val inStream = body.byteStream()
                var lastLogTime = 0L

                while (inStream.read(buffer).also { read = it } != -1) {
                    fos.write(buffer, 0, read)
                    current += read

                    val progress = if (totalLength > 0) (current.toFloat() / totalLength).coerceIn(0f, 1f) else 0f
                    val now = System.currentTimeMillis()
                    if (now - lastLogTime > 400L || current == totalLength) {
                        lastLogTime = now
                        _state.value = _state.value.copy(
                            engineDownloadProgress = progress,
                            statusMessage = "Téléchargement $label: ${(progress * 100).toInt()}%"
                        )
                    }
                }
                fos.flush()
            }
        }
        return destFile.exists() && destFile.length() > 0
    }

