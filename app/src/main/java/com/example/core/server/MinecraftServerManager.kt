    private fun resolveServerDirectory(): File {
        val hasManager = try {
            Build.VERSION.SDK_INT >= Build.VERSION_CODES.R && Environment.isExternalStorageManager()
        } catch (_: Throwable) {
            false
        }
        if (hasManager) {
            val extDir = File(Environment.getExternalStorageDirectory(), "MinecraftServer")
            if (extDir.exists() || extDir.mkdirs()) {
                try {
                    val test = File(extDir, ".mc_test")
                    test.writeText("test")
                    test.delete()
                    return extDir
                } catch (_: Exception) {}
            }
        }
        val appSpecific = context.getExternalFilesDir("MinecraftServer") ?: File(context.filesDir, "MinecraftServer")
        appSpecific.mkdirs()
        return appSpecific
    }

